"""
AutoClip Studio - Video Processor
Final video export with burned-in subtitles, audio processing, and quality checks.
"""

import asyncio
import subprocess
from pathlib import Path
from typing import Dict, Any, List, Optional

from auto_clip_studio.utils.config import Config
from auto_clip_studio.utils.logger import get_logger
from auto_clip_studio.models.job import Clip

logger = get_logger(__name__)


class VideoProcessor:
    """Final video processing and export."""

    def __init__(self, config: Config):
        self.config = config

    async def export_final_clip(
        self,
        clip: Clip,
        output_path: Path,
        subtitles_path: Optional[Path] = None
    ) -> Path:
        """
        Export final clip with burned-in subtitles.
        Returns path to exported file.
        """
        if not clip.video_path:
            raise ValueError("Clip has no rendered video path")

        source_path = Path(clip.video_path)
        if not source_path.exists():
            raise FileNotFoundError(f"Rendered video not found: {source_path}")

        output_path.parent.mkdir(parents=True, exist_ok=True)

        # Build FFmpeg command with subtitle burning
        cmd = self._build_export_command(source_path, output_path, subtitles_path)

        await self._run_ffmpeg(cmd)

        # Verify output
        if not output_path.exists():
            raise RuntimeError("Export failed: output file not created")

        # Quick validation
        duration = await self._get_video_duration(output_path)
        if abs(duration - clip.duration) > 1.0:
            logger.warning(f"Duration mismatch: expected {clip.duration:.1f}s, got {duration:.1f}s")

        logger.info(f"Exported final clip: {output_path} ({duration:.1f}s)")
        return output_path

    def _build_export_command(
        self,
        source_path: Path,
        output_path: Path,
        subtitles_path: Optional[Path] = None
    ) -> List[str]:
        """Build FFmpeg command for final export."""
        cmd = [
            "ffmpeg", "-y",
            "-i", str(source_path),
        ]

        # Video filters
        video_filters = []

        # Add subtitles if provided
        if subtitles_path and subtitles_path.exists():
            # Escape path for FFmpeg filter
            sub_path = str(subtitles_path).replace("\\", "/").replace(":", "\\:")
            video_filters.append(f"subtitles='{sub_path}'")

        # Ensure correct format
        video_filters.append("format=yuv420p")

        if video_filters:
            cmd.extend(["-vf", ",".join(video_filters)])

        # Audio: ensure good quality
        cmd.extend([
            "-c:v", self.config.video_codec,
            "-preset", self.config.video_preset,
            "-crf", str(self.config.video_crf),
            "-c:a", self.config.audio_codec,
            "-b:a", self.config.audio_bitrate,
            "-r", str(self.config.default_fps),
            "-pix_fmt", "yuv420p",
            "-movflags", "+faststart",
            "-metadata", f"title=AutoClip Studio - {clip.id}",
            "-metadata", "comment=Generated by AutoClip Studio",
            str(output_path)
        ])

        return cmd

    async def _run_ffmpeg(self, cmd: List[str]):
        """Run FFmpeg command asynchronously."""
        logger.debug(f"Running FFmpeg: {' '.join(cmd)}")

        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE
        )

        stdout, stderr = await proc.communicate()

        if proc.returncode != 0:
            error_msg = stderr.decode() if stderr else "Unknown error"
            logger.error(f"FFmpeg failed (exit {proc.returncode}): {error_msg}")
            raise RuntimeError(f"FFmpeg error: {error_msg}")

    async def _get_video_duration(self, video_path: Path) -> float:
        """Get video duration using ffprobe."""
        try:
            cmd = [
                "ffprobe", "-v", "error",
                "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1",
                str(video_path)
            ]
            proc = await asyncio.create_subprocess_exec(
                *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
            )
            stdout, _ = await proc.communicate()
            return float(stdout.decode().strip())
        except Exception:
            return 0.0

    async def verify_sync(
        self,
        video_path: Path,
        audio_reference_path: Path,
        check_points: List[float]
    ) -> Dict[str, Any]:
        """
        Verify audio-video sync at specific checkpoints.
        Returns sync analysis results.
        """
        results = {
            "video_path": str(video_path),
            "reference_path": str(audio_reference_path),
            "checks": [],
            "overall_sync": "unknown"
        }

        for checkpoint in check_points:
            # Extract audio from video at checkpoint
            video_audio = await self._extract_audio_segment(video_path, checkpoint, 2.0)
            ref_audio = await self._extract_audio_segment(audio_reference_path, checkpoint, 2.0)

            if video_audio and ref_audio:
                # Cross-correlation to find offset
                offset = await self._calculate_offset(video_audio, ref_audio)
                results["checks"].append({
                    "time": checkpoint,
                    "offset_ms": offset * 1000,
                    "in_sync": abs(offset) < 0.1  # Within 100ms
                })

        # Determine overall sync
        offsets = [c["offset_ms"] for c in results["checks"]]
        if offsets:
            avg_offset = sum(offsets) / len(offsets)
            max_offset = max(abs(o) for o in offsets)

            if max_offset < 100:
                results["overall_sync"] = "good"
            elif max_offset < 300:
                results["overall_sync"] = "acceptable"
            else:
                results["overall_sync"] = "poor"

            results["avg_offset_ms"] = avg_offset
            results["max_offset_ms"] = max_offset

        return results

    async def _extract_audio_segment(
        self,
        video_path: Path,
        start: float,
        duration: float
    ) -> Optional[Path]:
        """Extract audio segment to temporary WAV file."""
        import tempfile
        temp_dir = Path(tempfile.gettempdir()) / "autoclip_sync"
        temp_dir.mkdir(exist_ok=True)

        output_path = temp_dir / f"sync_check_{video_path.stem}_{start:.1f}.wav"

        cmd = [
            "ffmpeg", "-y",
            "-ss", str(start),
            "-t", str(duration),
            "-i", str(video_path),
            "-vn",
            "-ac", "1",
            "-ar", "16000",
            "-c:a", "pcm_s16le",
            str(output_path)
        ]

        try:
            proc = await asyncio.create_subprocess_exec(
                *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
            )
            await proc.communicate()

            if proc.returncode == 0 and output_path.exists():
                return output_path
        except Exception:
            pass

        return None

